use serde::{Deserialize, Serialize};
use std::{fs, path::PathBuf, sync::Mutex};

#[derive(Clone, Debug, Default, Deserialize, Serialize)]
#[serde(default, rename_all = "camelCase")]
pub struct AppConfig {
    pub model: Option<ModelConfig>,
    pub view: ViewConfig,
}

#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ModelConfig {
    pub name: String,
    pub file: String,
}

#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(default, rename_all = "camelCase")]
pub struct ViewConfig {
    pub framing: String,
    pub distance: Option<f64>,
}

impl Default for ViewConfig {
    fn default() -> Self {
        Self {
            framing: "bust".into(),
            distance: None,
        }
    }
}

impl ViewConfig {
    fn validate(&self) -> Result<(), String> {
        if !["face", "bust", "half_body", "full_body"].contains(&self.framing.as_str())
            || self
                .distance
                .is_some_and(|v| !v.is_finite() || !(0.35..=10.0).contains(&v))
        {
            return Err("Invalid camera settings".into());
        }
        Ok(())
    }
}

pub struct ConfigStore {
    directory: PathBuf,
    lock: Mutex<()>,
}

impl ConfigStore {
    pub fn new(directory: PathBuf) -> Self {
        Self {
            directory,
            lock: Mutex::new(()),
        }
    }

    fn read(&self) -> Result<AppConfig, String> {
        match fs::read(self.directory.join("config.json")) {
            Ok(bytes) => serde_json::from_slice(&bytes).map_err(|e| e.to_string()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(AppConfig::default()),
            Err(e) => Err(e.to_string()),
        }
    }

    fn write(&self, config: &AppConfig) -> Result<(), String> {
        fs::create_dir_all(&self.directory).map_err(|e| e.to_string())?;
        let temporary = self.directory.join("config.json.tmp");
        fs::write(
            &temporary,
            serde_json::to_vec_pretty(config).map_err(|e| e.to_string())?,
        )
        .map_err(|e| e.to_string())?;
        fs::rename(temporary, self.directory.join("config.json")).map_err(|e| e.to_string())
    }

    pub fn load(&self) -> Result<AppConfig, String> {
        let _guard = self.lock.lock().map_err(|e| e.to_string())?;
        let mut config = self.read()?;
        if config.view.validate().is_err() {
            config.view = ViewConfig::default();
        }
        Ok(config)
    }

    pub fn save_view(&self, view: ViewConfig) -> Result<(), String> {
        view.validate()?;
        let _guard = self.lock.lock().map_err(|e| e.to_string())?;
        let mut config = self.read()?;
        config.view = view;
        self.write(&config)
    }

    pub fn read_model(&self) -> Result<Option<Vec<u8>>, String> {
        let _guard = self.lock.lock().map_err(|e| e.to_string())?;
        self.read()?
            .model
            .map(|model| {
                // Config files must not redirect reads outside the application directory.
                if !model.file.ends_with(".vrm")
                    || model.file.contains(['/', '\\', ':'])
                    || model.file.starts_with('.')
                {
                    return Err("Invalid saved model filename".into());
                }
                fs::read(self.directory.join(model.file)).map_err(|e| e.to_string())
            })
            .transpose()
    }

    pub fn save_model(&self, name: String, data: Vec<u8>) -> Result<(), String> {
        let _guard = self.lock.lock().map_err(|e| e.to_string())?;
        let mut config = self.read()?;
        fs::create_dir_all(&self.directory).map_err(|e| e.to_string())?;
        let file = format!("{}.vrm", uuid::Uuid::new_v4());
        let path = self.directory.join(&file);
        fs::write(&path, data).map_err(|e| e.to_string())?;
        let previous = config.model.replace(ModelConfig { name, file });
        if let Err(error) = self.write(&config) {
            let _ = fs::remove_file(path);
            return Err(error);
        }
        if let Some(previous) = previous {
            // Only remove files generated by this store.
            if previous
                .file
                .strip_suffix(".vrm")
                .is_some_and(|s| uuid::Uuid::parse_str(s).is_ok())
            {
                let _ = fs::remove_file(self.directory.join(previous.file));
            }
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn restores_model_and_view_across_restarts() {
        let directory =
            std::env::temp_dir().join(format!("vessel-config-{}", uuid::Uuid::new_v4()));
        let store = ConfigStore::new(directory.clone());
        assert!(store.load().unwrap().model.is_none());
        store.save_model("first.vrm".into(), vec![1, 2, 3]).unwrap();
        store
            .save_view(ViewConfig {
                framing: "full_body".into(),
                distance: Some(3.2),
            })
            .unwrap();
        store.save_model("second.vrm".into(), vec![4, 5]).unwrap();
        let restarted = ConfigStore::new(directory.clone());
        let config = restarted.load().unwrap();
        assert_eq!(config.model.unwrap().name, "second.vrm");
        assert_eq!(config.view.framing, "full_body");
        assert_eq!(config.view.distance, Some(3.2));
        assert_eq!(restarted.read_model().unwrap(), Some(vec![4, 5]));
        assert_eq!(fs::read_dir(&directory).unwrap().count(), 2);
        assert!(store
            .save_view(ViewConfig {
                framing: "bust".into(),
                distance: Some(f64::NAN)
            })
            .is_err());
        assert_eq!(store.load().unwrap().view.distance, Some(3.2));
        fs::remove_dir_all(directory).unwrap();
    }
}
